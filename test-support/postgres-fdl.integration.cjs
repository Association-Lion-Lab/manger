test('FDL migration 003 vers 004 conserve les données et peut être répétée',{timeout:60000},async t=>{
  const fixture=await postgresFixture(t),owner=fixture.migrationPool;
  await owner.query('CREATE SCHEMA manger_meta; CREATE TABLE manger_meta.schema_migrations(version integer PRIMARY KEY,name text COLLATE "C" NOT NULL,checksum text COLLATE "C" NOT NULL,applied_at timestamptz NOT NULL DEFAULT now())');
  for(const name of ['001-initial','002-transfer-state','003-household-restore']){
    const migration=require('../db/migrations/'+name);await owner.query(migration.sql);
    await owner.query('INSERT INTO manger_meta.schema_migrations(version,name,checksum) VALUES($1,$2,$3)',[migration.version,migration.name,createHash('sha256').update(migration.sql).digest('hex')]);
  }
  await permissions(owner,'manger_test_app');
  await owner.query("INSERT INTO household.recipes(title,minutes,servings) VALUES('Recette existante',25,2)");
  await owner.query('UPDATE manger_meta.schema_migrations SET structure_checksum=$1 WHERE version=3',[await structureFingerprint(owner)]);
  assert.deepEqual(await migrateSchema(owner,'manger_test_app'),{version:4,applied:[4]});
  assert.equal((await owner.query('SELECT title FROM household.recipes')).rows[0].title,'Recette existante');
  assert.deepEqual(await migrateSchema(owner,'manger_test_app'),{version:4,applied:[]});
  const folder=await mkdtemp(join(tmpdir(),'manger-fdl-schema-'));t.after(()=>rm(folder,{recursive:true,force:true}));
  const secret=join(folder,'migration-password');await writeFile(secret,owner.options.password,{mode:0o600});
  const {stdout}=await require('node:util').promisify(require('node:child_process').execFile)(process.execPath,[join(__dirname,'..','postgres-schema.js'),'--apply'],{
    timeout:20000,windowsHide:true,env:{SystemRoot:process.env.SystemRoot,PATH:process.env.PATH,MANGER_PG_HOST:'127.0.0.1',MANGER_PG_PORT:String(fixture.port),MANGER_PG_DATABASE:'manger_test',MANGER_PG_USER:'manger_test_app',MANGER_PG_MIGRATION_USER:'manger_test_migrator',MANGER_PG_MIGRATION_PASSWORD_FILE:secret,MANGER_PG_TLS:'disable-local'}});
  assert.deepEqual(JSON.parse(stdout),{version:4,applied:[]});assert.equal(stdout.includes(owner.options.password),false);
});

test('FDL PostgreSQL : import atomique, versions et retrait sans faux article',{timeout:60000},async t=>{
  const {database:db}=await databaseFixture(t),recipes=postgresRecipes(db),store=postgresFdl(db);
  const link={origin:'https://fdl.example',clientOrigin:'https://manger.example',token:'private-token'};
  await store.setLink(link);
  const value=validateRecipe(recipeDraft());
  const source={origin:link.origin,fdlId:'12',version:1,metadata:{author:'Auteur',licence:'CC-BY-SA-4.0',seasons:['hiver']}};
  const imported=await store.importCopy(value,source,link);
  assert.equal((await store.importCopy(value,source,link)),'already-imported');
  await recipes.save({...value,title:'Version maison'},imported.id);
  assert.equal((await store.copies())[0].modified,true);
  await store.applyStates(link,[{recipeId:imported.id,state:'published',version:2}]);
  assert.equal((await store.copies())[0].availableVersion,2);
  await store.skipUpdate(imported.id);
  await store.applyStates(link,[{recipeId:imported.id,state:'published',version:2}]);
  assert.equal((await store.copies())[0].availableVersion,null);
  await store.applyStates(link,[{recipeId:imported.id,state:'published',version:3}]);
  await store.applyUpdate(imported.id,{...value,title:'Version FDL'},3,source.metadata,link);
  assert.equal((await store.copies())[0].modified,false);
  const normalBackup=await postgresHouseholdBackup(db)();
  assert.equal(decodeHousehold(normalBackup).fdl[0].metadata.author,'Auteur');
  const failing=postgresFdl({...db,transaction:work=>db.transaction(tx=>work({query:(sql,args)=>sql.startsWith('INSERT INTO household.fdl_copies')?Promise.reject(new Error('synthetic metadata failure')):tx.query(sql,args)}))});
  const before=await recipes.read();await assert.rejects(failing.importCopy(value,{...source,fdlId:'13'},link));assert.deepEqual(await recipes.read(),before);
  await db.query("INSERT INTO household.meals(date,slot,location,occasion,people,recipe_id,title) VALUES('2026-11-03','soir','home','regular',2,$1,'Titre du repas conservé')",[imported.id]);
  await store.applyStates(link,[{recipeId:imported.id,state:'removed'}]);
  const removed=(await recipes.read()).find(r=>r.id===imported.id);
  assert.equal(removed.fdl.removed,true);assert.deepEqual(removed.ingredients,[]);
  assert.deepEqual(await require('../db/calculations').postgresCalculations(db).shoppingList('2026-11-02'),[]);
  assert.equal((await db.query('SELECT title FROM household.meals')).rows[0].title,'Titre du repas conservé');
  assert.equal((await store.notices()).length,1);
  const dishCopy=await store.importCopy({...value,title:'Plat individuel'},{...source,fdlId:'14'},link);
  const member=(await db.query("INSERT INTO household.members(name,diet) VALUES('Camille','vegetarian') RETURNING id")).rows[0].id;
  const meal=(await db.query("INSERT INTO household.meals(date,slot,location,occasion,people,title) VALUES('2026-11-04','soir','home','regular',1,'Assiettes conservées') RETURNING id")).rows[0].id;
  await db.query('INSERT INTO household.meal_dishes(meal_id,member_id,recipe_id,portions) VALUES($1,$2,$3,1)',[meal,member,dishCopy.id]);
  await recipes.setFavorite(dishCopy.id,true);await recipes.setNote(dishCopy.id,5,'Note locale');
  await store.applyStates(link,[{recipeId:dishCopy.id,state:'removed'}]);
  assert.equal((await db.query('SELECT recipe_id::float8 AS id FROM household.meal_dishes WHERE meal_id=$1',[meal])).rows[0].id,dishCopy.id);
  assert.equal((await db.query('SELECT title FROM household.meals WHERE id=$1',[meal])).rows[0].title,'Assiettes conservées');
  const neutral=(await recipes.read()).find(r=>r.id===dishCopy.id);assert.equal(neutral.favorite,false);assert.equal(neutral.note,undefined);
  await store.clearLink(link.token);assert.equal(await store.link(),null);
  assert.equal((await store.copies()).length,2);
  await store.setLink(link);
  const bytes=await postgresHouseholdBackup(db)();
  assert.equal(JSON.parse(bytes).version,2);assert.equal(bytes.includes('private-token'),false);
  assert.equal(decodeHousehold(bytes).fdl[0].removed,true);
  const directory=await mkdtemp(join(tmpdir(),'manger-fdl-restore-'));
  t.after(()=>rm(directory,{recursive:true,force:true}));
  const restore=createPostgresRestore(db,{recoveryDirectory:join(directory,'recovery')});t.after(restore.clear);
  const preview=await restore.preview(Readable.from([bytes]));await restore.apply(preview.token);
  assert.equal(await store.link(),null);assert.equal((await store.copies())[0].removed,true);
  assert.deepEqual(await store.notices(),[]);
  await store.setLink(link);
  const concurrent=await Promise.all([store.importCopy(value,{...source,fdlId:'13'},link),store.importCopy(value,{...source,fdlId:'13'},link)]);
  assert.equal(concurrent.filter(result=>result==='already-imported').length,1);
  assert.equal((await store.copies()).filter(copy=>copy.fdlId==='13').length,1);
  await store.clearLink();const unchanged=await recipes.read();
  await assert.rejects(store.importCopy(value,{...source,fdlId:'16'},link));assert.deepEqual(await recipes.read(),unchanged);
});
