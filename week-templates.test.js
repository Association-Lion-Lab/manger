const test = require('node:test');
const assert = require('node:assert/strict');
const { once } = require('node:events');
const { createApp, createDatabase } = require('./server');

test('semaines types : enregistrement, application atomique et suppression', async t => {
  const db = createDatabase(':memory:'), server = createApp(db);
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(() => { server.close(); db.close(); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (path, method = 'GET', data) => fetch(base + path, { method, headers: data ? { 'content-type': 'application/json' } : {}, body: data ? JSON.stringify(data) : undefined });
  const post = (path, data) => request(path, 'POST', data);
  const start = '2026-09-21', target = '2026-09-28';
  assert.equal(db.prepare('PRAGMA user_version').get().user_version, 4);
  assert.equal((await post('/api/week-templates', { name: 'Vide', start })).status, 400);
  const member = await (await post('/api/members', { name: 'Julie', diet: 'vegetarian' })).json();
  const recipes = db.prepare('SELECT id, title FROM recipes ORDER BY id LIMIT 2').all();
  const common = { date: start, slot: 'soir', location: 'home', occasion: 'regular', people: 2, recipeId: recipes[0].id, title: recipes[0].title, assignments: [], dishes: [] };
  const individual = { date: '2026-09-22', slot: 'midi', location: 'home', occasion: 'regular', people: 1, recipeId: null, title: 'Assiette de Julie', assignments: [], dishes: [{ memberId: member.id, recipeId: recipes[1].id, portions: 1 }] };
  assert.equal((await post('/api/meals', common)).status, 200);
  assert.equal((await post('/api/meals', individual)).status, 200);
  const created = await post('/api/week-templates', { name: ' Semaine facile ', start });
  assert.equal(created.status, 201); const template = await created.json();
  assert.deepEqual({ name: template.name, mealCount: template.mealCount }, { name: 'Semaine facile', mealCount: 2 });
  assert.equal((await post('/api/week-templates', { name: 'Semaine facile', start })).status, 400);
  assert.deepEqual((await (await request('/api/week-templates')).json()).map(item => [item.name, item.mealCount]), [['Semaine facile', 2]]);
  db.prepare('DELETE FROM meals').run();
  const applied = await post(`/api/week-templates/${template.id}/apply`, { targetStart: target });
  assert.deepEqual(await applied.json(), { added: 2 });
  const copied = db.prepare('SELECT date, slot, recipe_id AS recipeId FROM meals ORDER BY date, slot').all();
  assert.deepEqual(copied.map(meal => meal.date), [target, '2026-09-29']);
  assert.equal(db.prepare('SELECT recipe_id AS recipeId FROM meal_dishes').get().recipeId, recipes[1].id);
  const beforeConflict = db.prepare('SELECT COUNT(*) AS n FROM meals').get().n;
  assert.equal((await post(`/api/week-templates/${template.id}/apply`, { targetStart: target })).status, 400);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM meals').get().n, beforeConflict);
  for (const invalid of ['2026-09-29', 'non']) assert.equal((await post(`/api/week-templates/${template.id}/apply`, { targetStart: invalid })).status, 400);
  assert.equal((await request(`/api/week-templates/${template.id}`, 'DELETE')).status, 200);
  assert.deepEqual(await (await request('/api/week-templates')).json(), []);
  assert.equal((await request(`/api/week-templates/${template.id}`, 'DELETE')).status, 400);
});
